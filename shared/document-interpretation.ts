export function validateDocumentInterpretationRequest(
  requestId: string,
  text: string,
) {
  if (!/^[A-Za-z0-9_-]{8,128}$/.test(requestId))
    throw new Error('DOCUMENT_REQUEST_INVALID');
  if (!text.trim() || text.length > DOCUMENT_LIMITS.interpretationCharacters)
    throw new Error('DOCUMENT_SELECTION_SIZE');
  if (
    /(?:file|content):\/\/|data:[^\s;,]+[;,]|\/(?:Users|private|var|data\/user)\/|[A-Za-z]:\\/i.test(
      text,
    )
  )
    throw new Error('DOCUMENT_LOCAL_REFERENCE');
}
